#!/usr/bin/env node
// Bundles the runner and the world scenario into src/play-bundle.ts, so the
// playground's container can be handed them without a git checkout. Run it
// after changing runner/ or scenarios/world/ (a test checks it is current).
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const files = {};
for (const f of ['lib.mjs', 'plan.mjs', 'run.mjs', 'scripted-agent.mjs', 'superpose.mjs', 'play-director.mjs']) {
  files[`runner/${f}`] = readFileSync(join(root, 'runner', f), 'utf8');
}
const walk = (dir) => {
  for (const name of readdirSync(join(root, dir)).sort()) {
    const rel = `${dir}/${name}`;
    if (statSync(join(root, rel)).isDirectory()) walk(rel);
    else files[rel] = readFileSync(join(root, rel), 'utf8');
  }
};
walk('scenarios/world');
writeFileSync(
  join(root, 'src/play-bundle.ts'),
  `// Generated by scripts/build-play.mjs from runner/ and scenarios/world/. Do not edit.\nexport const PLAY_FILES: Record<string, string> = ${JSON.stringify(files)};\n`,
);
console.log(`bundled ${Object.keys(files).length} files`);
